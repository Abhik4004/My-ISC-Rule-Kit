package com.iscrulekit;

import java.io.IOException;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

/** Writes an RDK-style JUnit 4 test class from a cases file: one @Test per case, inputs and expectations inline. */
final class JUnitGen {
    private JUnitGen() {}

    static String testClass(String className, String rulePath, RuleType type, List<TestSuite.Case> cases, Path casesFile) {
        StringBuilder b = new StringBuilder();
        b.append("import com.iscrulekit.RuleTester;\n");
        b.append("import org.junit.Test;\n\n");
        b.append("/**\n");
        b.append(" * JUnit tests for ").append(rulePath).append(type == null ? "" : " (" + type.label + " rule)").append(".\n");
        b.append(" * Generated by 'iscrule junit-gen' from ").append(casesFile.getFileName()).append(". Edit freely, or regenerate after\n");
        b.append(" * adding cases with 'iscrule add-test'.\n");
        b.append(" *\n");
        b.append(" * Run:  iscrule junit ").append(Path.of(rulePath).getParent() == null ? "." : Path.of(rulePath).getParent().toString().replace('\\', '/')).append("\n");
        b.append(" * (or from an IDE, with the kit and JUnit 4 on the test classpath and the kit folder as working directory)\n");
        b.append(" */\n");
        b.append("public class ").append(className).append(" {\n\n");
        b.append("    private static final RuleTester RULE = RuleTester.load(\"").append(rulePath.replace('\\', '/')).append("\");\n");

        Set<String> used = new HashSet<>();
        int i = 0;
        for (TestSuite.Case c : cases) {
            i++;
            String method = methodName(i, c.name(), used);
            b.append("\n    /** ").append(c.name().replace("*/", "* /")).append(" */\n");
            b.append("    @Test\n");
            b.append("    public void ").append(method).append("() {\n");
            b.append("        RULE.run(").append(textBlock(Json.pretty(c.inputs()), 12)).append(")");
            if (c.expectError()) {
                b.append("\n            .assertError(").append(javaString(c.expectErrorContains() == null ? "" : c.expectErrorContains())).append(");\n");
                b.append("    }\n");
                continue;
            }
            b.append("\n            .assertNoError()");
            if (c.hasExpect()) b.append("\n            .assertReturns(").append(textBlock(Json.pretty(c.expect() == null ? Json.toNode(null) : c.expect()), 12)).append(")");
            if (c.expectChanged() != null) b.append("\n            .assertChanged(").append(textBlock(Json.pretty(c.expectChanged()), 12)).append(")");
            for (String log : c.expectLogContains()) b.append("\n            .assertLogContains(").append(javaString(log)).append(")");
            b.append(";\n    }\n");
        }
        b.append("}\n");
        return b.toString();
    }

    static String methodName(int i, String name, Set<String> used) {
        StringBuilder s = new StringBuilder();
        boolean up = false;
        String clean = name.replaceAll("\\[recorded - review\\]", "").replaceFirst("^\\s*\\d+[\\s.:)_-]+", ""); // "04 Add..." -> "Add..."
        for (char ch : clean.toCharArray()) {
            if (Character.isLetterOrDigit(ch) && ch < 128) {
                s.append(s.isEmpty() ? Character.toLowerCase(ch) : up ? Character.toUpperCase(ch) : ch);
                up = false;
            } else up = true;
            if (s.length() >= 60) break;
        }
        String base = String.format("test%02d_%s", i, s.isEmpty() ? "case" : s);
        String m = base;
        for (int k = 2; !used.add(m); k++) m = base + "_" + k;
        return m;
    }

    /** A Java text block holding {@code text} (backslashes doubled so the JSON reads back unchanged). */
    static String textBlock(String text, int indent) {
        String pad = " ".repeat(indent);
        StringBuilder b = new StringBuilder("\"\"\"\n");
        for (String line : text.replace("\r\n", "\n").split("\n", -1))
            b.append(pad).append(line.replace("\\", "\\\\").replace("\"\"\"", "\\\"\"\"")).append('\n');
        return b.append(pad).append("\"\"\"").toString();
    }

    static String javaString(String s) {
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\"";
    }

    /** Class name for a rule file: Foo.java -> FooTest. */
    static String classNameFor(Path rule) {
        String n = rule.getFileName().toString();
        n = n.substring(0, n.indexOf('.') > 0 ? n.indexOf('.') : n.length());
        String id = n.replaceAll("[^A-Za-z0-9_]", "");
        if (id.isEmpty() || !Character.isJavaIdentifierStart(id.charAt(0))) id = "Rule" + id;
        return Character.toUpperCase(id.charAt(0)) + id.substring(1) + "Test";
    }

    static Path write(Path rule, Path cases, RuleType type) throws IOException {
        List<TestSuite.Case> list = TestSuite.load(cases);
        String cls = classNameFor(rule);
        Path out = rule.resolveSibling(cls + ".java");
        String rulePath;
        try {
            rulePath = Path.of("").toAbsolutePath().relativize(rule.toAbsolutePath()).toString();
        } catch (IllegalArgumentException e) { // different drive
            rulePath = rule.toAbsolutePath().toString();
        }
        java.nio.file.Files.writeString(out, testClass(cls, rulePath, type, list, cases), java.nio.charset.StandardCharsets.UTF_8);
        return out;
    }

    static boolean isTestFile(Path p) {
        String n = p.getFileName().toString();
        return n.endsWith("Test.java") || n.endsWith("Tests.java");
    }
}
